namespace CSCourse.Contracts.Kafka;

/// <summary>
/// Запрос на публикацию события о создании бронирования.
/// Используется для уведомления других сервисов (через Kafka) о том, 
/// что бронирование инициировано и прошло первичную валидацию.
/// </summary>
public record BookingCreated
{
    /// <summary>
    /// Уникальный идентификатор бронирования.
    /// Выступает в роли CorrelationId для сквозного отслеживания жизненного цикла бронирования
    /// в распределённой системе. Должен совпадать с Id в BookingConfirmed.
    /// </summary>
    public required Guid Id { get; init; }

    /// <summary>
    /// Идентификатор мероприятия, к которому относится бронирование.
    /// Должен ссылаться на существующий EventId в системе.
    /// </summary>
    public required Guid EventId { get; init; }

    /// <summary>
    /// Идентификатор пользователя, инициировавшего бронирование.
    /// Используется для проверки прав и аудита действий.
    /// </summary>
    public required Guid UserId { get; init; }

    /// <summary>
    /// Количество мест, запрашиваемых в рамках бронирования.
    /// Положительное целое число. В текущей версии проекта может быть равно 1, 
    /// но оставлено как поле для поддержки групповых/пакетных бронирований в будущем.
    /// </summary>
    public required int Quantity { get; init; }

    /// <summary>
    /// Дата и время создания запроса на бронирование.
    /// Фиксируется на стороне Booking.Service. Позволяет отслеживать задержки 
    /// между созданием и подтверждением бронирования.
    /// </summary>
    public DateTime CreatedAt { get; init; }
}