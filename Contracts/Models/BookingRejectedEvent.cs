namespace CSCourse.Contracts.Models;

/// <summary>
/// Событие об отклонении (отказе в подтверждении) бронирования.
/// Публикуется через Kafka, когда бронирование не может быть подтверждено 
/// по бизнес-правилам (например, лимит мест исчерпан, событие отменено и т.п.).
/// </summary>
public record BookingRejectedEvent
{
    /// <summary>
    /// Уникальный идентификатор бронирования, которое было отклонено.
    /// </summary>
    /// <remarks>
    /// Соответствует Id созданного бронирования. Позволяет связать отказ 
    /// с первоначальной инициацией и отследить жизненный цикл брони.
    /// </remarks>
    public required Guid Id { get; init; }

    /// <summary>
    /// Идентификатор мероприятия, к которому относилось бронирование.
    /// </summary>
    /// <remarks>
    /// Помогает определить, по какому событию произошёл отказ, 
    /// и при необходимости обновить статистику или уведомления.
    /// </remarks>
    public required Guid EventId { get; init; }

    /// <summary>
    /// Идентификатор пользователя, которому отказали в бронировании.
    /// </summary>
    /// <remarks>
    /// Нужен для отправки пользователю уведомления об отказе 
    /// и для аудита действий в системе.
    /// </remarks>
    public required Guid UserId { get; init; }

    /// <summary>
    /// Код причины отклонения бронирования.
    /// </summary>
    /// <remarks>
    /// Стандартизированный код (например, ENUM или строка), позволяющий 
    /// другим сервисам автоматически реагировать на тип отказа. 
    /// Примеры: "SEATS_UNAVAILABLE", "EVENT_CANCELLED", "USER_BLOCKED".
    /// </remarks>
    public required string RejectionCode { get; init; }

    /// <summary>
    /// Человекочитаемое описание причины отказа.
    /// </summary>
    /// <remarks>
    /// Предназначено для отображения пользователю или записи в лог. 
    /// Может содержать детали, полезные для поддержки (например, сколько мест осталось).
    /// </remarks>
    public required string Message { get; init; }

    /// <summary>
    /// Дата и время фиксации отказа в бронировании.
    /// </summary>
    /// <remarks>
    /// Позволяет отслеживать временные задержки и анализировать частоту отказов 
    /// по периодам времени.
    /// </remarks>
    public required DateTime RejectedAt { get; init; }
}
